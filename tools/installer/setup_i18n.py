PREFIXES = tuple(key for key in MESSAGES if key.endswith(': '))


def translate(source, language):
    if language == 'en':
        return source
    index = 0 if language == 'zh-CN' else 1
    if source in MESSAGES:
        return MESSAGES[source][index]
    for prefix in PREFIXES:
        if source.startswith(prefix):
            return MESSAGES[prefix][index] + translate(source[len(prefix):], language)
    return source
